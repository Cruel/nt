// The cache proof reads large binary Assets repeatedly. Constructing a string
// through single-character stream iterators is especially costly in the
// unoptimized, gcov-instrumented CI build. Keep full-byte proof semantics,
// but read into a sized buffer with one bulk I/O operation.
std::optional<std::string> read_exact_file(const fs::path& path)
{
    count_validation_work<WorkCounter::FileByteReads>();
    std::error_code error;
    const auto size = fs::file_size(path, error);
    if (error || size > static_cast<std::uintmax_t>(std::numeric_limits<std::streamsize>::max()))
        return std::nullopt;
    std::ifstream stream(path, std::ios::binary);
    if (!stream)
        return std::nullopt;
    std::string bytes(static_cast<std::size_t>(size), '\0');
    if (!stream.read(bytes.data(), static_cast<std::streamsize>(bytes.size())) ||
        stream.peek() != std::char_traits<char>::eof() || fs::file_size(path, error) != size ||
        error)
        return std::nullopt;
    count_validation_work<WorkCounter::FileBytesRead>(bytes.size());
    return bytes;
}

// Intentionally NOT the TypeScript authoring-cache semantic identity. Native
// diagnostic semantics must be independently bumped when validation changes.
constexpr std::string_view kContract = "noveltea.native-clean-validation.v1";
constexpr std::string_view kSemanticKey = "workspace-v1/native-project-validation-598";
constexpr std::string_view kSemanticFingerprint = NOVELTEA_NATIVE_VALIDATION_FINGERPRINT;
constexpr std::string_view kRelative = ".noveltea/cache/authoring/native-clean-current.json";
// Discriminate cached source generations from pre-cutover SHA-256 evidence.
constexpr std::string_view kSourceRevisionAlgorithm = "xxh3-128";
constexpr std::string_view kAssetProofAlgorithm = "xxh3-128";

std::string cache_project_root(const fs::path& root)
{
    const auto canonical = fs::canonical(root);
#ifdef _WIN32
    // std::filesystem::canonical can preserve the 8.3 alias used to open a
    // directory. ScriptC's CLI process and Electron's Node-API worker may
    // enter the same Project through RUNNER~1 and runneradmin respectively.
    // Compare their *expanded* physical roots, not their spelling, before
    // accepting a cache generated by the other host.
    const auto& wide = canonical.native();
    const DWORD required = GetLongPathNameW(wide.c_str(), nullptr, 0);
    if (!required || required > 32768)
        throw std::runtime_error("Cannot resolve the Windows Project cache root.");
    std::wstring expanded(required, L'\0');
    const DWORD count = GetLongPathNameW(wide.c_str(), expanded.data(), required);
    if (!count || count >= required)
        throw std::runtime_error("Cannot expand the Windows Project cache root.");
    expanded.resize(count);
    return fs::path(expanded).generic_string();
#else
    return canonical.generic_string();
#endif
}

bool safe_cache_path(const fs::path& root)
{
    fs::path partial = root;
    for (const auto* segment : {".noveltea", "cache", "authoring", "native-clean-current.json"}) {
        partial /= segment;
        const auto status = fs::symlink_status(partial);
        if (status.type() == fs::file_type::symlink ||
            (status.type() != fs::file_type::not_found &&
             status.type() != fs::file_type::directory &&
             !(partial == root / kRelative && status.type() == fs::file_type::regular)))
            return false;
    }
    return true;
}

bool transactions_settled(const fs::path& root)
{
    if (fs::exists(root / ".noveltea/asset-import.lock"))
        return false;
    const auto imports = root / ".noveltea/asset-import-staging";
    if (fs::exists(imports) && (!fs::is_directory(imports) || !fs::is_empty(imports)))
        return false;
    const auto transactions = root / ".noveltea/transactions";
    const auto status = fs::symlink_status(transactions);
    if (status.type() == fs::file_type::not_found)
        return true;
    return status.type() == fs::file_type::directory && fs::is_empty(transactions);
}

std::optional<std::map<std::string, std::string>>
exact_proof(const fs::path& root, const std::map<std::string, std::string>* observed,
            std::string_view phase,
            std::map<std::string, std::pair<std::string, std::string>>* resident_proofs,
            bool watcher_fenced)
{
    if (!observed)
        return std::nullopt;
    auto revisions = *observed;
    const auto canonical_root = fs::canonical(root);
    // SourceAuthority avoids hashing large binary Assets for ordinary watcher
    // polling. Clean result admission is stricter: no size+mtime-only proof.
    for (auto& [relative, revision] : revisions) {
        if (!revision.starts_with("physical:"))
            continue;
        const auto physical_revision = revision;
        if (watcher_fenced && resident_proofs) {
            const auto found = resident_proofs->find(relative);
            if (found != resident_proofs->end() && found->second.first == physical_revision) {
                revision = found->second.second;
                continue;
            }
        }
        const fs::path path = root / relative;
        const auto contained = fs::weakly_canonical(path).lexically_relative(canonical_root);
        if (fs::symlink_status(path).type() != fs::file_type::regular || contained.empty() ||
            *contained.begin() == "..")
            return std::nullopt;
        const auto bytes = read_exact_file(path);
        if (!bytes)
            return std::nullopt;
        count_validation_work<WorkCounter::ContentHashes>();
        count_validation_work<WorkCounter::ContentBytesHashed>(bytes->size());
        revision = noveltea::core::xxh3_128_revision(*bytes);
        if (watcher_fenced && resident_proofs)
            (*resident_proofs)[relative] = {physical_revision, revision};
        trace_exact_asset_proof(phase, relative, bytes->size());
    }
    return revisions;
}

Json source_metadata(const fs::path& root, const std::map<std::string, std::string>& revisions)
{
    Json value = Json::object();
    for (const auto& [path, revision] : revisions) {
        const auto physical = root / path;
        const auto status = fs::symlink_status(physical);
        Json source = Json::object();
        source["revision"] = revision;
        source["type"] = static_cast<int>(status.type());
        source["size"] = fs::is_regular_file(status) ? fs::file_size(physical) : 0;
        source["modified"] =
            fs::exists(status)
                ? std::to_string(fs::last_write_time(physical).time_since_epoch().count())
                : std::string{};
        value[path] = std::move(source);
    }
    return value;
}

Json diagnostics_json(const std::vector<Diagnostic>& diagnostics)
{
    Json result = Json::array();
    for (const auto& diagnostic : diagnostics) {
        Json item = Json::object();
        item["path"] = diagnostic.path;
        item["code"] = diagnostic.code;
        item["message"] = diagnostic.message;
        item["severity"] = diagnostic.severity;
        item["sourcePath"] = diagnostic.source_path;
        if (diagnostic.line)
            item["line"] = *diagnostic.line;
        if (diagnostic.column)
            item["column"] = *diagnostic.column;
        result.push_back(std::move(item));
    }
    return result;
}

std::string source_path_for_owner(std::string_view owner)
{
    if (owner == "traits" || owner == "editor")
        return std::string(owner) + ".yaml";
    if (owner.starts_with("i18n/"))
        return std::string(owner);
    if (owner.starts_with("layouts/"))
        return "records/" + std::string(owner) + "/layout.yaml";
    if (owner.find('/') != std::string_view::npos)
        return "records/" + std::string(owner) + ".yaml";
    return {};
}

struct CachedValidation {
    RoomSessionSnapshot snapshot;
    Json resident;
    Json stages;
    std::map<std::string, std::string> saved_revisions;
    std::map<std::string, std::string> changed_revisions;
};

std::optional<CachedValidation>
read_clean_cache(const fs::path& root, const std::map<std::string, std::string>& revisions,
                 const RoomSessionSnapshot& source)
{
    try {
        if (!safe_cache_path(root))
            return std::nullopt;
        const auto path = root / kRelative;
        if (!fs::is_regular_file(path) || fs::file_size(path) > 32 * 1024 * 1024)
            return std::nullopt;
        std::ifstream input(path, std::ios::binary);
        const auto value = Json::parse(input);
        if (!value.is_object() || value.size() != 12 || value.at("contract") != kContract ||
            value.at("semanticKey") != kSemanticKey ||
            value.at("semanticFingerprint") != kSemanticFingerprint ||
            value.at("sourceRevisionAlgorithm") != kSourceRevisionAlgorithm ||
            value.at("assetProofAlgorithm") != kAssetProofAlgorithm ||
            value.at("projectRoot") != cache_project_root(root) || !value.at("sources").is_object())
            return std::nullopt;
        std::map<std::string, std::string> saved_revisions;
        for (const auto& entry : value.at("sources").object_range()) {
            const auto& metadata = entry.value();
            if (!metadata.is_object() || metadata.size() != 4 ||
                !metadata.at("revision").is_string() || !metadata.at("type").is_integer<int>() ||
                !metadata.at("size").is_number() || !metadata.at("modified").is_string())
                return std::nullopt;
            saved_revisions.emplace(std::string(entry.key()),
                                    metadata.at("revision").as<std::string>());
        }
        const auto current_metadata = source_metadata(root, revisions);
        std::map<std::string, std::string> changed_revisions;
        for (const auto& entry : value.at("sources").object_range()) {
            const std::string path(entry.key());
            if (!current_metadata.contains(path) || current_metadata.at(path) != entry.value())
                changed_revisions.emplace(path,
                                          revisions.contains(path) ? revisions.at(path) : "absent");
        }
        for (const auto& [path, revision] : revisions)
            if (!saved_revisions.contains(path))
                changed_revisions.emplace(path, revision);
        // A different Manifest changes the interpretation of every owner.
        // There is no defensible partial graph under a different root contract.
        if (changed_revisions.contains("project.yaml"))
            return std::nullopt;
        // A matching physical source generation alone does not establish that
        // the persisted *derived* diagnostics and normalized records survived
        // intact. Bind the semantic payload without coupling it to optional
        // external stages, which may independently fall back on corruption.
        // This is a corruption check, not
        // an authentication mechanism for hostile same-user cache writers.
        if (!value.at("payloadRevision").is_string())
            return std::nullopt;
        auto payload = value;
        payload.erase("payloadRevision");
        payload.erase("stageRevision");
        payload.erase("stages");
        if (value.at("payloadRevision") != noveltea::core::xxh3_128_revision(payload.to_string()))
            return std::nullopt;
        const auto& result = value.at("result");
        if (!result.is_object() || result.size() != 2 || !result.at("valid").is_bool() ||
            !result.at("diagnostics").is_array() || result.at("diagnostics").size() > 10000)
            return std::nullopt;
        RoomSessionSnapshot snapshot = source;
        snapshot.valid = result.at("valid").as<bool>();
        snapshot.diagnostics.clear();
        bool errors = false;
        for (const auto& entry : result.at("diagnostics").array_range()) {
            if (!entry.is_object() || entry.size() < 5 || entry.size() > 7 ||
                !entry.at("path").is_string() || !entry.at("code").is_string() ||
                !entry.at("message").is_string() || !entry.at("severity").is_string() ||
                !entry.at("sourcePath").is_string())
                return std::nullopt;
            Diagnostic issue{entry.at("path").as<std::string>(), entry.at("code").as<std::string>(),
                             entry.at("message").as<std::string>(),
                             entry.at("severity").as<std::string>()};
            issue.source_path = entry.at("sourcePath").as<std::string>();
            if (issue.severity != "error" && issue.severity != "warning" &&
                issue.severity != "info")
                return std::nullopt;
            errors |= issue.severity == "error";
            if (entry.contains("line")) {
                if (!entry.at("line").is_integer<int>() || entry.at("line").as<int>() <= 0)
                    return std::nullopt;
                issue.line = entry.at("line").as<int>();
            }
            if (entry.contains("column")) {
                if (!entry.at("column").is_integer<int>() || entry.at("column").as<int>() <= 0)
                    return std::nullopt;
                issue.column = entry.at("column").as<int>();
            }
            snapshot.diagnostics.push_back(std::move(issue));
        }
        if (snapshot.valid == errors)
            return std::nullopt;
        const auto& resident = value.at("resident");
        const auto valid_diagnostics = [](const Json& diagnostics) {
            if (!diagnostics.is_array() || diagnostics.size() > 10000)
                return false;
            for (const auto& issue : diagnostics.array_range()) {
                if (!issue.is_object() || issue.size() < 5 || issue.size() > 7 ||
                    !issue.at("path").is_string() || !issue.at("code").is_string() ||
                    !issue.at("message").is_string() || !issue.at("sourcePath").is_string() ||
                    !issue.at("severity").is_string())
                    return false;
                const auto severity = issue.at("severity").as<std::string>();
                if (severity != "error" && severity != "warning" && severity != "info")
                    return false;
                for (const auto* coordinate : {"line", "column"})
                    if (issue.contains(coordinate) && (!issue.at(coordinate).is_integer<int>() ||
                                                       issue.at(coordinate).as<int>() <= 0))
                        return false;
            }
            return true;
        };
        if (!resident.is_null() &&
            (!resident.is_object() || resident.size() != 3 ||
             !resident.at("contributions").is_object() || !resident.at("spatial").is_object() ||
             !(resident.at("global").is_null() || resident.at("global").is_object())))
            return std::nullopt;
        if (resident.is_object())
            for (const auto& entry : resident.at("contributions").object_range()) {
                const auto owner = std::string(entry.key());
                const auto& contribution = entry.value();
                if (!contribution.is_object() || contribution.size() != 4 ||
                    !contribution.at("dependencies").is_array() ||
                    !contribution.at("valid").is_bool() ||
                    !valid_diagnostics(contribution.at("diagnostics")))
                    return std::nullopt;
                const auto& record = contribution.at("record");
                if (!record.is_object() || record.size() != 6 || !record.at("bytes").is_string() ||
                    !record.at("source").is_string() || !record.at("normalized").is_string() ||
                    !record.at("valid").is_bool() || !record.at("contract").is_string() ||
                    !valid_diagnostics(record.at("diagnostics")))
                    return std::nullopt;
                // A cold hit is allowed to defer creating RoomSessions, not
                // to accept contributor bytes different from its proved YAML
                // generation. Otherwise a well-shaped corrupted ledger would
                // yield cached diagnostics until the first later mutation.
                const auto source_path = source_path_for_owner(owner);
                if (source_path.empty() || !saved_revisions.contains(source_path) ||
                    exact_source_revision(record.at("bytes").as<std::string>()) !=
                        saved_revisions.at(source_path))
                    return std::nullopt;
                for (const auto& dependency : contribution.at("dependencies").array_range()) {
                    if (!dependency.is_object() || dependency.size() != 2 ||
                        !dependency.at("owner").is_string() || !dependency.at("paths").is_array())
                        return std::nullopt;
                    for (const auto& path : dependency.at("paths").array_range())
                        if (!path.is_string())
                            return std::nullopt;
                }
            }
        if (resident.is_object()) {
            const auto& spatial = resident.at("spatial");
            const auto& global = resident.at("global");
            if (!spatial.is_object() || spatial.size() != 2 ||
                !spatial.at("cursorSettings").is_string() || !spatial.at("owners").is_object())
                return std::nullopt;
            for (const auto& entry : spatial.at("owners").object_range()) {
                const auto owner = std::string(entry.key());
                if (!(owner.starts_with("rooms/") || owner.starts_with("maps/") ||
                      owner.starts_with("interactables/")) ||
                    !resident.at("contributions").contains(owner) || !entry.value().is_object() ||
                    entry.value().size() != 2 || !entry.value().at("accepted").is_bool() ||
                    !valid_diagnostics(entry.value().at("diagnostics")))
                    return std::nullopt;
            }
            // Older ledgers included text-only diagnostics in this global
            // contribution. Reusing them after the split could publish stale
            // source findings; rebuild those ledgers instead.
            if (!global.is_null() &&
                (!global.is_object() || global.size() != 4 || !global.at("inputValid").is_bool() ||
                 !global.at("outputValid").is_bool() ||
                 global.at("textDiagnosticsSeparate") != true ||
                 !valid_diagnostics(global.at("diagnostics"))))
                return std::nullopt;
        }
        Json stages = Json::null();
        const auto& stored_stages = value.at("stages");
        if (value.at("stageRevision").is_string() &&
            (stored_stages.is_null() || stored_stages.is_object()) &&
            value.at("stageRevision") ==
                noveltea::core::xxh3_128_revision(stored_stages.to_string()))
            stages = stored_stages;
        return CachedValidation{std::move(snapshot), resident, stages, std::move(saved_revisions),
                                std::move(changed_revisions)};
    } catch (...) {
        return std::nullopt; // Optional acceleration; malformed or old formats always miss.
    }
}

bool publish_clean_cache(const fs::path& root, const std::map<std::string, std::string>& revisions,
                         const RoomSessionSnapshot& snapshot, const Json& resident,
                         const Json& stages = Json::null())
{
    try {
        if (!safe_cache_path(root))
            return false;
        const fs::path path = root / kRelative;
        fs::create_directories(path.parent_path());
        if (!safe_cache_path(root))
            return false;
        Json value = Json::object();
        value["contract"] = std::string(kContract);
        value["semanticKey"] = std::string(kSemanticKey);
        value["semanticFingerprint"] = std::string(kSemanticFingerprint);
        value["sourceRevisionAlgorithm"] = std::string(kSourceRevisionAlgorithm);
        value["assetProofAlgorithm"] = std::string(kAssetProofAlgorithm);
        value["projectRoot"] = cache_project_root(root);
        value["sources"] = source_metadata(root, revisions);
        value["result"] = Json::object();
        value["result"]["valid"] = snapshot.valid;
        value["result"]["diagnostics"] = diagnostics_json(snapshot.diagnostics);
        value["resident"] = resident;
        value["stages"] = stages;
        value["stageRevision"] = noveltea::core::xxh3_128_revision(stages.to_string());
        auto semantic_payload = value;
        semantic_payload.erase("stages");
        semantic_payload.erase("stageRevision");
        value["payloadRevision"] = noveltea::core::xxh3_128_revision(semantic_payload.to_string());
        const auto serialized = value.to_string() + '\n';
        // Repeated validations must not replace an already current ledger.
        // Reusing identical bytes also avoids resetting the quiet-window clock
        // of an unrelated resident watching Project-local private state.
        if (fs::is_regular_file(path) && fs::file_size(path) == serialized.size()) {
            const auto previous = read_exact_file(path);
            if (previous && *previous == serialized)
                return true;
        }
        static std::atomic<std::uint64_t> sequence{0};
        const auto staged = fs::path(
            path.string() + "." +
            std::to_string(std::chrono::steady_clock::now().time_since_epoch().count()) + "." +
            std::to_string(std::random_device{}()) + "." + std::to_string(++sequence) + ".tmp");
        {
            std::ofstream output(staged, std::ios::binary | std::ios::trunc);
            if (!output)
                return false;
            output << serialized;
            output.flush();
            if (!output) {
                std::error_code ignored;
                output.close();
                fs::remove(staged, ignored);
                return false;
            }
        }
        // A concurrent publisher can win; both entries are admitted only by
        // re-proving the entire input manifest, not by trusting the rename.
        try {
            if (!safe_cache_path(root) || !transactions_settled(root) ||
                value.at("sources") != source_metadata(root, revisions)) {
                std::error_code ignored;
                fs::remove(staged, ignored);
                return false;
            }
#ifdef _WIN32
            if (!MoveFileExW(staged.c_str(), path.c_str(),
                             MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH))
                throw std::runtime_error("Cannot replace native validation cache.");
#else
            fs::rename(staged, path);
#endif
            return true;
        } catch (...) {
            std::error_code ignored;
            fs::remove(staged, ignored);
            throw;
        }
    } catch (...) {
        // Never make validation fail due to a missing/read-only cache directory.
    }
    return false;
}
