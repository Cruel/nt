// This file is deliberately never removed: unlinking a locked inode lets a
// second process lock its replacement while the first still owns the old one.
// Both the CLI owner and the Node-API worker hold the same canonical-root lock.
struct ProjectSession::CacheLease {
#ifdef _WIN32
    HANDLE file = INVALID_HANDLE_VALUE;
    OVERLAPPED offset{};
#else
    int file = -1;
#endif

    ~CacheLease()
    {
#ifdef _WIN32
        if (file != INVALID_HANDLE_VALUE) {
            UnlockFileEx(file, 0, 1, 0, &offset);
            CloseHandle(file);
        }
#else
        if (file >= 0) {
            (void)flock(file, LOCK_UN);
            (void)close(file);
        }
#endif
    }

    bool acquire(const fs::path& root)
    {
        try {
            const auto parent = root / ".noveltea/cache/authoring";
            // Optional cache storage is not an authority to traverse symlinks.
            if (!safe_cache_path(root))
                return false;
            fs::create_directories(parent);
            if (!safe_cache_path(root))
                return false;
            const auto path = parent / "native-clean-writer.lock";
            if (fs::symlink_status(path).type() == fs::file_type::symlink)
                return false;
#ifdef _WIN32
            file = CreateFileW(path.c_str(), GENERIC_READ | GENERIC_WRITE,
                               FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_ALWAYS,
                               FILE_ATTRIBUTE_NORMAL | FILE_FLAG_OPEN_REPARSE_POINT, nullptr);
            if (file == INVALID_HANDLE_VALUE)
                return false;
            BY_HANDLE_FILE_INFORMATION info{};
            if (!GetFileInformationByHandle(file, &info) ||
                (info.dwFileAttributes &
                 (FILE_ATTRIBUTE_REPARSE_POINT | FILE_ATTRIBUTE_DIRECTORY)) ||
                !LockFileEx(file, LOCKFILE_EXCLUSIVE_LOCK | LOCKFILE_FAIL_IMMEDIATELY, 0, 1, 0,
                            &offset)) {
                CloseHandle(file);
                file = INVALID_HANDLE_VALUE;
                return false;
            }
#else
            file = ::open(path.c_str(), O_CREAT | O_RDWR | O_CLOEXEC | O_NOFOLLOW, 0600);
            if (file < 0)
                return false;
            struct stat info {};
            if (fstat(file, &info) != 0 || !S_ISREG(info.st_mode) ||
                flock(file, LOCK_EX | LOCK_NB) != 0) {
                (void)close(file);
                file = -1;
                return false;
            }
#endif
            return true;
        } catch (...) {
            return false;
        }
    }
};

ProjectSession::ProjectSession(std::unique_ptr<RoomSession> source,
                               std::unique_ptr<SourceAuthority> source_authority, fs::path root,
                               std::string traits_baseline_json)
    : source_(std::move(source)), source_authority_(std::move(source_authority)),
      root_(std::move(root)), traits_baseline_json_(std::move(traits_baseline_json))
{
}

ProjectSession::~ProjectSession()
{
    if (resident_cache_maintenance_ && owns_clean_cache_lease()) {
        try {
            maintain_clean_cache(true);
        } catch (...) {
            // A best-effort shutdown flush cannot prevent session destruction.
        }
    }
}

bool ProjectSession::owns_clean_cache_lease() const noexcept { return cache_lease_ != nullptr; }

bool ProjectSession::acquire_cache_lease_if_due()
{
    if (cache_lease_)
        return true;
    const auto now = std::chrono::steady_clock::now();
    if (now < cache_next_lease_attempt_)
        return false;
    cache_next_lease_attempt_ = now + std::chrono::seconds(5);
    auto candidate = std::make_unique<CacheLease>();
    if (!candidate->acquire(root_))
        return false;
    cache_lease_ = std::move(candidate);
    cache_maintenance_pending_ = true;
    return true;
}

void ProjectSession::initialize_cache_lease()
{
    // Initial lease acquisition never performs semantic validation. Even if
    // optional cache storage is unwritable, the Project remains interactive.
    (void)acquire_cache_lease_if_due();
}

void ProjectSession::note_disk_cache_change()
{
    cache_maintenance_pending_ = true;
    cache_quiet_until_ = std::chrono::steady_clock::now() + std::chrono::seconds(5);
    cache_next_maintenance_attempt_ = {};
    cache_stage_revisions_.reset();
    cache_stage_json_.clear();
    cache_stage_builder_ = {};
}

void ProjectSession::enable_resident_cache_maintenance()
{
    resident_cache_maintenance_ = true;
    cache_maintenance_pending_ = true;
    const auto now = std::chrono::steady_clock::now();
    // An owner taking over a quiet Project need not wait a second five-second
    // window. Any untrusted clock or more recent source conservatively delays.
    cache_quiet_until_ = now;
    if (!owns_clean_cache_lease())
        return; // Nonowners do no cache-only source enumeration or stat calls.
    if (const auto* revisions = verified_source_revisions_view()) {
        try {
            const auto file_now = fs::file_time_type::clock::now();
            for (const auto& [path, revision] : *revisions) {
                (void)revision;
                const auto modified = fs::last_write_time(root_ / path);
                const auto age = file_now - modified;
                if (age < std::chrono::seconds(5)) {
                    const auto remaining = std::chrono::seconds(5) - age;
                    cache_quiet_until_ = std::max(
                        cache_quiet_until_,
                        now + std::chrono::duration_cast<std::chrono::steady_clock::duration>(
                                  remaining));
                }
            }
        } catch (...) {
            cache_quiet_until_ = now + std::chrono::seconds(5);
        }
    }
}

bool ProjectSession::maintain_clean_cache(bool shutdown, bool already_observed)
{
    if (!resident_cache_maintenance_ || !acquire_cache_lease_if_due())
        return false;
    // Only the elected writer is allowed to poll for proactive maintenance.
    if (!shutdown && !already_observed) {
        try {
            (void)observe_sources();
        } catch (...) {
            return false; // Optional maintenance must not disrupt active sessions.
        }
    }
    if (!cache_maintenance_pending_)
        return !shutdown && std::chrono::steady_clock::now() >= cache_quiet_until_;
    if (!shutdown && (std::chrono::steady_clock::now() < cache_quiet_until_ ||
                      std::chrono::steady_clock::now() < cache_next_maintenance_attempt_))
        return false;
    // Serialize through the same resident validator, not a second disk reader.
    cache_maintenance_active_ = true;
    cache_maintenance_shutdown_ = shutdown;
    cache_maintenance_published_ = false;
    try {
        const auto result = validate_clean_project();
        if ((result.cache_hit || cache_maintenance_published_) &&
            (shutdown || std::chrono::steady_clock::now() >= cache_quiet_until_))
            cache_maintenance_pending_ = false;
    } catch (...) {
        cache_maintenance_active_ = false;
        cache_maintenance_shutdown_ = false;
        cache_next_maintenance_attempt_ =
            std::chrono::steady_clock::now() + std::chrono::seconds(5);
        return false; // Cached results are optional; retry on a later idle tick.
    }
    cache_maintenance_active_ = false;
    cache_maintenance_shutdown_ = false;
    if (cache_maintenance_pending_)
        cache_next_maintenance_attempt_ =
            std::chrono::steady_clock::now() + std::chrono::seconds(5);
    return !shutdown && !cache_maintenance_pending_;
}

void ProjectSession::revoke_clean_validation()
{
    validation_snapshot_.reset();
    validation_records_.clear();
    validation_source_revisions_.clear();
    validation_source_paths_.clear();
    validation_source_errors_.clear();
    validation_contributions_.clear();
    validation_normalized_records_.clear();
    validation_reference_consumers_.clear();
    validation_global_contribution_.reset();
    validation_source_locations_.clear();
    validation_spatial_contributions_.clear();
    validation_spatial_cursor_settings_.clear();
    validation_pending_uncertain_ = true;
}

void ProjectSession::hydrate_clean_validation()
{
    if (!pending_clean_hydration_)
        return;
    auto hydrate = std::move(pending_clean_hydration_);
    pending_clean_hydration_ = {};
    pending_clean_resident_json_.clear();
    if (!hydrate())
        revoke_clean_validation();
}

ProjectSession::CleanValidation ProjectSession::validate_clean_project(bool initially_observed,
                                                                       bool defer_valid_publication)
{
    const auto resident_state = [&]() -> Json {
        if (pending_clean_hydration_)
            return Json::parse(pending_clean_resident_json_);
        // A contributor bundle is optional acceleration, never the authority
        // for a clean result. Malformed physical YAML source errors cannot be
        // reconstructed from record sessions and therefore omit this bundle.
        if (!validation_snapshot_ || !validation_source_errors_.empty() ||
            validation_contributions_.size() != validation_records_.size())
            return Json::null();
        Json contributors = Json::object();
        for (const auto& [owner, contribution] : validation_contributions_) {
            if (contribution.dirty)
                return Json::null();
            contributors[owner] = Json::object();
            contributors[owner]["valid"] = contribution.valid;
            contributors[owner]["diagnostics"] = diagnostics_json(contribution.diagnostics);
            const auto& record = *validation_records_.at(owner);
            const auto snapshot = record.snapshot();
            auto& saved = contributors[owner]["record"];
            saved = Json::object();
            saved["bytes"] = record.disk_source_;
            saved["source"] = snapshot.source_json;
            saved["normalized"] = snapshot.normalized_json;
            saved["valid"] = snapshot.valid;
            saved["diagnostics"] = diagnostics_json(snapshot.diagnostics);
            saved["contract"] = record.validation_contract_;
            auto& dependencies = contributors[owner]["dependencies"];
            dependencies = Json::array();
            if (const auto indexed = validation_normalized_records_.find(owner);
                indexed != validation_normalized_records_.end())
                for (const auto& dependency : indexed->second.dependencies) {
                    Json item = Json::object();
                    item["owner"] = dependency.target_owner;
                    item["paths"] = dependency.target_impact_paths;
                    dependencies.push_back(std::move(item));
                }
        }
        Json spatial = Json::object();
        spatial["cursorSettings"] = validation_spatial_cursor_settings_;
        spatial["owners"] = Json::object();
        for (const auto& [owner, contribution] : validation_spatial_contributions_) {
            auto& saved = spatial["owners"][owner];
            saved = Json::object();
            saved["accepted"] = contribution.accepted;
            saved["diagnostics"] = diagnostics_json(contribution.diagnostics);
        }
        Json resident = Json::object();
        resident["contributions"] = std::move(contributors);
        resident["spatial"] = std::move(spatial);
        resident["global"] = Json::null();
        if (validation_global_contribution_) {
            auto& global = resident["global"];
            global = Json::object();
            global["inputValid"] = validation_global_contribution_->input_valid;
            global["outputValid"] = validation_global_contribution_->output_valid;
            global["textDiagnosticsSeparate"] = true;
            global["diagnostics"] = diagnostics_json(validation_global_contribution_->diagnostics);
        }
        return resident;
    };

    const auto hydrate_resident = [this](const Json& payload,
                                         const std::map<std::string, std::string>& revisions,
                                         const std::map<std::string, std::string>& changed,
                                         const RoomSessionSnapshot& cached) {
        if (!payload.is_object())
            return false;
        // The cache's revision proof has already established a physical source
        // generation. Reopening every resident owner without these scopes
        // needlessly reads and decodes the entire Project a second time.
        // A final proof below still rejects any intervening physical change.
        ScopedVerifiedProjectSources observed(*source_authority_);
        ScopedYamlDecodeCache decoding(*yaml_decode_cache_);
        // Project admission already validated localization against the *new*
        // physical source generation. Reindexing unchanged ledger owners can
        // transiently invalidate that exact current result. Retain it rather
        // than treating cold graph materialization as a source edit.
        const auto admitted_localization = localization_cache_;
        try {
            const auto& contributions = payload.at("contributions");
            const auto& spatial = payload.at("spatial");
            const auto parse_diagnostics = [](const Json& array) {
                if (!array.is_array() || array.size() > 10000)
                    throw std::runtime_error("Invalid resident diagnostics.");
                std::vector<Diagnostic> values;
                for (const auto& entry : array.array_range()) {
                    if (!entry.is_object() || !entry.at("path").is_string() ||
                        !entry.at("code").is_string() || !entry.at("message").is_string() ||
                        !entry.at("severity").is_string() || !entry.at("sourcePath").is_string())
                        throw std::runtime_error("Invalid resident diagnostic entry.");
                    Diagnostic issue{entry.at("path").as<std::string>(),
                                     entry.at("code").as<std::string>(),
                                     entry.at("message").as<std::string>(),
                                     entry.at("severity").as<std::string>()};
                    issue.source_path = entry.at("sourcePath").as<std::string>();
                    if (issue.severity != "error" && issue.severity != "warning" &&
                        issue.severity != "info")
                        throw std::runtime_error("Unknown resident diagnostic severity.");
                    if (entry.contains("line"))
                        issue.line = entry.at("line").as<int>();
                    if (entry.contains("column"))
                        issue.column = entry.at("column").as<int>();
                    values.push_back(std::move(issue));
                }
                return values;
            };
            std::map<std::string, ValidationContribution> prepared_contributions;
            for (const auto& entry : contributions.object_range()) {
                const std::string owner(entry.key());
                if (changed.contains(source_path_for_owner(owner)))
                    continue;
                const auto& source = entry.value();
                if (!source.is_object() || source.size() != 4 || !source.at("valid").is_bool() ||
                    !source.at("record").is_object())
                    return false;
                prepared_contributions.emplace(
                    std::string(entry.key()),
                    ValidationContribution{source.at("valid").as<bool>(), false,
                                           parse_diagnostics(source.at("diagnostics"))});
            }
            if (spatial.size() != 2 || !spatial.at("cursorSettings").is_string() ||
                !spatial.at("owners").is_object())
                return false;
            std::map<std::string, ValidationResult> prepared_spatial;
            for (const auto& entry : spatial.at("owners").object_range()) {
                const auto owner = std::string(entry.key());
                const auto& contribution = entry.value();
                if (!contribution.is_object() || contribution.size() != 2 ||
                    !contribution.at("accepted").is_bool())
                    return false;
                prepared_spatial.emplace(
                    owner, ValidationResult{contribution.at("accepted").as<bool>(), "",
                                            parse_diagnostics(contribution.at("diagnostics"))});
            }

            std::map<std::string, std::unique_ptr<RoomSession>> prepared_records;
            std::map<std::string, std::string> prepared_revisions;
            std::set<std::string> prepared_paths;
            for (const auto& file : file_inventory()) {
                const auto& path = file.path;
                if (file.kind != ProjectFileKind::TrackedSource || !path.ends_with(".yaml") ||
                    path == "project.yaml")
                    continue;
                std::string owner;
                if (path == "editor.yaml")
                    owner = "editor";
                else if (path == "traits.yaml")
                    owner = "traits";
                else if (path.starts_with("i18n/"))
                    owner = path;
                else if (path.starts_with("records/")) {
                    const auto rest = path.substr(sizeof("records/") - 1);
                    const auto slash = rest.find('/');
                    if (slash == std::string::npos)
                        continue;
                    const auto family = rest.substr(0, slash);
                    const auto source_id = rest.substr(slash + 1);
                    if (family == "layouts") {
                        if (!source_id.ends_with("/layout.yaml"))
                            continue;
                        owner = family + "/" + source_id.substr(0, source_id.size() - 12);
                    } else {
                        if (source_id.find('/') != std::string::npos)
                            continue;
                        owner = family + "/" + source_id.substr(0, source_id.size() - 5);
                    }
                } else
                    continue;
                if (changed.contains(path))
                    continue;
                if (!revisions.contains(path) || !prepared_contributions.contains(owner))
                    return false;
                const auto& saved = contributions.at(owner).at("record");
                if (saved.size() != 6 || !saved.at("bytes").is_string() ||
                    !saved.at("source").is_string() || !saved.at("normalized").is_string() ||
                    !saved.at("valid").is_bool() || !saved.at("contract").is_string())
                    return false;
                const auto slash = owner.find('/');
                const auto id = slash == std::string::npos ? owner : owner.substr(slash + 1);
                auto record = std::unique_ptr<RoomSession>(
                    new RoomSession(root_ / path, id, saved.at("bytes").as<std::string>(),
                                    saved.at("source").as<std::string>()));
                if (record->disk_revision_ != revisions.at(path))
                    return false;
                record->is_editor_ = owner == "editor";
                record->is_traits_ = owner == "traits";
                record->is_localization_ = owner.starts_with("i18n/");
                record->is_map_ = owner.starts_with("maps/");
                record->record_family_ = owner.substr(0, slash);
                record->validation_contract_ = saved.at("contract").as<std::string>();
                RoomSessionSnapshot restored;
                restored.disk_source_revision = revisions.at(path);
                restored.source_json = record->working_json_;
                restored.baseline_json = record->disk_json_;
                restored.normalized_json = saved.at("normalized").as<std::string>();
                restored.valid = saved.at("valid").as<bool>();
                restored.diagnostics = parse_diagnostics(saved.at("diagnostics"));
                record->snapshot_cache_ = std::move(restored);
                prepared_paths.insert(path);
                prepared_revisions.emplace(path, revisions.at(path));
                prepared_records.emplace(owner, std::move(record));
            }
            if (prepared_contributions.size() != prepared_records.size())
                return false;
            std::map<std::string, IndexedNormalizedRecord> prepared_normalized;
            std::map<std::string, std::map<std::string, std::vector<std::string>>>
                prepared_consumers;
            for (const auto& entry : contributions.object_range()) {
                const std::string owner(entry.key());
                // Changed and deleted owners are *not* valid contributors, but
                // their old normalized identity and outgoing edges are needed
                // for the existing reverse-closure diff. Without the old
                // identity a deletion looks like absent -> absent and misses
                // surviving consumers of the deleted target.
                if (!prepared_records.contains(owner)) {
                    if (!changed.contains(source_path_for_owner(owner)))
                        return false;
                }
                IndexedNormalizedRecord indexed;
                indexed.normalized_json =
                    prepared_records.contains(owner)
                        ? prepared_records.at(owner)->snapshot().normalized_json
                        : entry.value().at("record").at("normalized").as<std::string>();
                for (const auto& dependency : entry.value().at("dependencies").array_range()) {
                    if (!dependency.is_object() || dependency.size() != 2 ||
                        !dependency.at("owner").is_string() || !dependency.at("paths").is_array())
                        return false;
                    indexed.dependencies.push_back(
                        {dependency.at("owner").as<std::string>(),
                         dependency.at("paths").as<std::vector<std::string>>()});
                }
                for (const auto& dependency : indexed.dependencies) {
                    auto& paths = prepared_consumers[dependency.target_owner][owner];
                    paths.insert(paths.end(), dependency.target_impact_paths.begin(),
                                 dependency.target_impact_paths.end());
                }
                prepared_normalized.emplace(owner, std::move(indexed));
            }
            std::optional<GlobalValidationContribution> prepared_global;
            const auto& global = payload.at("global");
            if (!global.is_null()) {
                if (!global.is_object() || global.size() != 4 ||
                    !global.at("inputValid").is_bool() || !global.at("outputValid").is_bool() ||
                    global.at("textDiagnosticsSeparate") != true)
                    return false;
                prepared_global = GlobalValidationContribution{
                    global.at("inputValid").as<bool>(), global.at("outputValid").as<bool>(),
                    parse_diagnostics(global.at("diagnostics"))};
            }
            // Install the whole resident contributor graph only after every
            // nested field has passed admission. No partial reverse index may
            // survive a malformed optional ledger.
            validation_records_ = std::move(prepared_records);
            validation_source_revisions_ = std::move(prepared_revisions);
            validation_source_paths_ = std::move(prepared_paths);
            validation_contributions_ = std::move(prepared_contributions);
            validation_normalized_records_ = std::move(prepared_normalized);
            validation_reference_consumers_ = std::move(prepared_consumers);
            validation_spatial_contributions_ = std::move(prepared_spatial);
            validation_spatial_cursor_settings_ = spatial.at("cursorSettings").as<std::string>();
            validation_global_contribution_ = std::move(prepared_global);
            validation_source_errors_.clear();
            for (const auto& [owner, record] : validation_records_)
                index_text_owner(owner, record->snapshot().source_json);
            localization_cache_ = admitted_localization;
            validation_snapshot_ = cached;
            validation_source_locations_.clear();
            return true;
        } catch (...) {
            return false;
        }
    };
    const auto clean = [&]() {
        if (source_->snapshot().dirty || !deleted_records_.empty() || !shader_overlays_.empty() ||
            !text_source_overlays_.empty())
            return false;
        for (const auto& [owner, record] : records_) {
            (void)owner;
            if (record->snapshot().dirty)
                return false;
        }
        return true;
    };
    const auto proof =
        [&](bool use_latest_observation = false,
            std::string_view phase =
                "cache-admission") -> std::optional<std::map<std::string, std::string>> {
        try {
            if (!transactions_settled(root_))
                return std::nullopt;
            if (!use_latest_observation) {
                const auto observation = observe_sources();
                if (observation.full_rescan || !observation.authoritative)
                    return std::nullopt;
            } else if (!source_authority_->verified_revisions_view()) {
                return std::nullopt;
            }
            // macOS FSEvents does not yet prove writes through a hard link
            // outside the watched Project; retain full-byte checks there.
#if defined(__APPLE__)
            constexpr bool inode_proof_supported = false;
#else
            constexpr bool inode_proof_supported = true;
#endif
            auto exact = exact_proof(
                root_, source_authority_->verified_revisions_view(), phase, &exact_asset_proofs_,
                inode_proof_supported && source_authority_->watcher_proof_available());
            return transactions_settled(root_) ? exact : std::nullopt;
        } catch (...) {
            // Cache IO and physical proof may fail independently of semantic
            // validation. Such failures always invalidate optional reuse.
            return std::nullopt;
        }
    };
    if (validation_pending_uncertain_) {
        // The watcher may have completed its recovery scan *before* this call.
        // In that case the full-rescan flag is no longer emitted by proof(),
        // but the former resident and imported semantic evidence is still
        // revoked until a fresh validation rebuilds the contributors.
        pending_clean_hydration_ = {};
        validation_snapshot_.reset();
        validation_source_revisions_.clear();
        validation_contributions_.clear();
        validation_spatial_contributions_.clear();
        validation_spatial_cursor_settings_.clear();
    }

    std::optional<std::map<std::string, std::string>> cache_admission_evidence;
    std::string offline_stage_evidence;
    if (clean() && !validation_pending_uncertain_ && !validation_snapshot_ &&
        validation_pending_source_revisions_.empty()) {
        if (const auto revisions = proof(initially_observed)) {
            // This is the same pre-validation source boundary. Cache lookup
            // itself cannot change tracked sources, and the independent
            // post-preparation proof must still match these exact digests.
            cache_admission_evidence = *revisions;
            if (auto cached = read_clean_cache(root_, *revisions, source_->snapshot())) {
                if (cached->resident.is_object()) {
                    // The public native owner can defer this proof until its
                    // post-preparation generation check. That independent
                    // check must compare every digest against cache admission
                    // before the cached result can be published to the CLI.
                    // Standalone/editor consumers still prove immediately.
                    const bool unchanged = cached->changed_revisions.empty();
                    if ((unchanged && defer_valid_publication && cached->snapshot.valid) ||
                        proof(false, "cache-final") == revisions) {
                        if (unchanged) {
                            if (cache_maintenance_active_ && owns_clean_cache_lease() &&
                                cache_stage_revisions_ == revisions &&
                                (cache_stage_builder_ || !cache_stage_json_.empty())) {
                                try {
                                    const auto stages =
                                        Json::parse(cache_stage_builder_ ? cache_stage_builder_()
                                                                         : cache_stage_json_);
                                    if (stages != cached->stages &&
                                        proof(true, "cache-stage-publication") == revisions)
                                        cache_maintenance_published_ =
                                            publish_clean_cache(root_, *revisions, cached->snapshot,
                                                                cached->resident, stages);
                                } catch (...) {
                                    // Invalid optional stage evidence never revokes semantics.
                                }
                            }
                            pending_clean_hydration_ =
                                [hydrate_resident, payload = cached->resident,
                                 revisions = *revisions, snapshot = cached->snapshot]() {
                                    return hydrate_resident(payload, revisions, {}, snapshot);
                                };
                            pending_clean_resident_json_ = cached->resident.to_string();
                            validation_snapshot_ = cached->snapshot;
                            ++validation_generation_;
                            validation_work_ = {};
                            if (defer_valid_publication && cached->snapshot.valid)
                                return {std::move(cached->snapshot), true,
                                        std::move(revisions),        cached->resident.to_string(),
                                        cached->stages.to_string(),  validation_generation_};
                            return {std::move(cached->snapshot), true};
                        }
                        // Offline differences are not a result hit. Admit only
                        // the old, exact-byte-proved *unaffected* contributors
                        // and let the normal resident dependency walker rebuild
                        // the changed owners and their consumer closure.
                        if (hydrate_resident(cached->resident, cached->saved_revisions,
                                             cached->changed_revisions, cached->snapshot)) {
                            if (cached->stages.is_object())
                                offline_stage_evidence = cached->stages.to_string();
                            SourceDelta offline;
                            for (const auto& [path, revision] : cached->changed_revisions) {
                                validation_pending_source_revisions_[path] = revision;
                                if (revision == "absent")
                                    offline.removed.push_back(path);
                                else if (!cached->saved_revisions.contains(path))
                                    offline.added.push_back(path);
                                else
                                    offline.changed.push_back(path);
                            }
                            for (const auto& path :
                                 source_authority_->affected_asset_records(offline))
                                if (path.starts_with("records/") && path.ends_with(".yaml"))
                                    validation_pending_asset_owners_.insert(
                                        path.substr(sizeof("records/") - 1,
                                                    path.size() - sizeof("records/") - 4));
                            // An unchanged ledger's raw top-level diagnostics
                            // are never returned across an offline edit.
                            validation_snapshot_ = cached->snapshot;
                        } else {
                            // An importer can reject the ledger after
                            // preparing some of its optional indexes. Never
                            // let a partially installed graph contaminate a
                            // subsequent authoritative validation.
                            revoke_clean_validation();
                        }
                        // The source authority is live and watching before
                        // reconciliation. Changes during import are rejected
                        // by the next physical generation fence.
                        cache_admission_evidence = *revisions;
                    } else {
                        source_authority_->coverage_lost();
                        validation_pending_uncertain_ = true;
                        trace_source_proof_event("cache-final", "fallback");
                    }
                } else if (cached->changed_revisions.empty() &&
                           proof(false, "cache-final") == revisions) {
                    // Inadmissible local YAML can retain its exact invalid
                    // diagnostic result, but has no safe contributor bundle.
                    validation_work_ = {};
                    return {std::move(cached->snapshot), true};
                }
                // Contributor hydration may have installed an optimistic
                // snapshot before the last physical proof failed. Revoke it
                // and force a fresh observation/rebuild on the miss path,
                // including when an Asset changed without metadata changing.
                if (!cached->resident.is_object()) {
                    source_authority_->coverage_lost();
                    validation_pending_uncertain_ = true;
                    trace_source_proof_event("cache-final", "fallback");
                }
            }
        }
    }
    // Cache publication must match the exact generation observed before
    // validation, not merely two identical post-validation manifests.
    const auto validated_input =
        clean() && !validation_pending_uncertain_
            ? (cache_admission_evidence ? std::move(cache_admission_evidence)
                                        : proof(initially_observed, "validation-pre"))
            : std::nullopt;
    auto snapshot = validate_project(validated_input.has_value(), defer_valid_publication);
    const bool completed = validation_snapshot_.has_value() &&
                           validation_snapshot_->working_revision == snapshot.working_revision &&
                           !validation_pending_uncertain_;
    // Rebuilt validation contributions retain their pinned exact source proof.
    if (clean() && completed && validated_input) {
        if (defer_valid_publication && snapshot.valid)
            return {std::move(snapshot), false, std::move(validated_input),
                    // The resident writer builds this whole-Project bundle
                    // only at its elected quiet-window publication, never on
                    // an ordinary saved-file validation request.
                    resident_cache_maintenance_ ? std::string{} : resident_state().to_string(),
                    std::move(offline_stage_evidence), validation_generation_};
        if (owns_clean_cache_lease() &&
            (!resident_cache_maintenance_ || cache_maintenance_active_) &&
            (!resident_cache_maintenance_ || cache_maintenance_shutdown_ ||
             std::chrono::steady_clock::now() >= cache_quiet_until_) &&
            proof(true, "validation-publication") == validated_input) {
            Json stages = Json::null();
            if (cache_stage_revisions_ == validated_input &&
                (cache_stage_builder_ || !cache_stage_json_.empty())) {
                try {
                    stages = Json::parse(cache_stage_builder_ ? cache_stage_builder_()
                                                              : cache_stage_json_);
                } catch (...) {
                    stages = Json::null();
                }
            }
            cache_maintenance_published_ =
                publish_clean_cache(root_, *validated_input, snapshot, resident_state(), stages);
        }
    }
    return {std::move(snapshot), false};
}

bool ProjectSession::publish_deferred_clean_validation(
    const CleanValidation& validated, const std::map<std::string, std::string>& post_revisions,
    std::string_view stages_json, std::function<std::string()> deferred_stages)
{
    if (!validated.deferred_exact_revisions)
        return true; // Standalone cache hits were already independently proven.
    // A delayed caller may race a newer *valid* resident generation. Reject
    // its publication token without revoking the newer generation's authority.
    if (validated.validation_generation != validation_generation_)
        return false;
    if (*validated.deferred_exact_revisions != post_revisions || !transactions_settled(root_) ||
        validation_pending_uncertain_ || !validation_pending_source_revisions_.empty() ||
        !validation_snapshot_ || !validated.snapshot.valid ||
        validation_snapshot_->working_revision != validated.snapshot.working_revision ||
        source_->snapshot().dirty || !deleted_records_.empty() || !shader_overlays_.empty() ||
        !text_source_overlays_.empty()) {
        trace_source_proof_event("validation-preparation-generation", "conflict");
        source_authority_->coverage_lost();
        validation_pending_uncertain_ = true;
        return false;
    }
    for (const auto& [owner, record] : records_) {
        (void)owner;
        if (record->snapshot().dirty)
            return false;
    }
    if (resident_cache_maintenance_) {
        cache_maintenance_pending_ = true;
        cache_stage_revisions_ = post_revisions;
        cache_stage_builder_ = std::move(deferred_stages);
        // A semantic-only repeat must not discard independently proved font
        // and shader stage evidence from a previously admitted cache hit.
        cache_stage_json_ = stages_json != "null" ? std::string(stages_json)
                            : validated.cache_hit ? validated.stages_json
                                                  : std::string{};
    } else if (owns_clean_cache_lease() &&
               (!validated.cache_hit || stages_json != "null" || deferred_stages)) {
        try {
            publish_clean_cache(
                root_, post_revisions, validated.snapshot,
                Json::parse(validated.deferred_resident_json),
                Json::parse(deferred_stages ? deferred_stages() : std::string(stages_json)));
        } catch (...) {
            // A malformed optional cache must never make a validated Project fail.
        }
    }
    return true;
}
