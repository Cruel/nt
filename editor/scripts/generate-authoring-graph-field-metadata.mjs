import { readFile, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { registerHooks } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

// Node 24 can erase TypeScript types. Only the build-time reviewer is loaded
// here; the generated runtime metadata never imports the reviewer or Zod schema.
// Resolve the extensionless relative TS imports used by the editor sources.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (!specifier.startsWith('.') || error.code !== 'ERR_MODULE_NOT_FOUND') throw error;
      for (const suffix of ['.ts', '.tsx', '/index.ts']) {
        try {
          return nextResolve(specifier + suffix, context);
        } catch (candidateError) {
          if (candidateError.code !== 'ERR_MODULE_NOT_FOUND') throw candidateError;
        }
      }
      throw error;
    }
  },
  load(url, context, nextLoad) {
    // Existing editor TS code imports generated JSON contracts without Node's
    // import attributes; they are bundled as normal modules in production.
    if (url.endsWith('.json')) {
      return {
        format: 'module',
        shortCircuit: true,
        source: `export default ${readFileSync(fileURLToPath(url), 'utf8')};`,
      };
    }
    return nextLoad(url, context);
  },
});

const editorRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const metadataRoot = path.join(editorRoot, 'src/shared/project-schema');
const outputPath = path.join(metadataRoot, 'authoring-graph-field-metadata.generated.ts');
const review = await import(
  pathToFileURL(path.join(metadataRoot, 'authoring-graph-field-metadata-review.ts')).href
);
review.assertAuthoringGraphFieldMetadataComplete();

const codes = new Map([
  ['{"kind":"none"}', 'n'],
  ['{"kind":"owner-contribution"}', 'o'],
  ['{"kind":"source-analysis"}', 's'],
  ['{"kind":"symbol-definition"}', 'y'],
  ['{"kind":"structural"}', 't'],
  ['{"kind":"value-dependent","classify":"asset-source-impact"}', 'a'],
  ['{"kind":"value-dependent","classify":"localization-catalog-entry"}', 'l'],
  ['{"kind":"value-dependent","classify":"property-assignment"}', 'p'],
  ['{"kind":"value-dependent","classify":"structural-variant"}', 'v'],
]);
const fields = review.AUTHORING_GRAPH_FIELD_METADATA;
const serializedPaths = fields.map(({ path }) => JSON.stringify(path));
const serializedCodes = fields.map(({ effect, path }) => {
  const code = codes.get(JSON.stringify(effect));
  if (!code)
    throw new Error(`Unknown reviewed graph effect for '${path}': ${JSON.stringify(effect)}`);
  return code;
});
const groupedPaths = [];
for (let offset = 0; offset < serializedPaths.length; offset += 12) {
  groupedPaths.push('  ' + serializedPaths.slice(offset, offset + 12).join(', ') + ',');
}
const groupedCodes = [];
for (let offset = 0; offset < serializedCodes.length; offset += 120) {
  groupedCodes.push(
    '  ' + JSON.stringify(serializedCodes.slice(offset, offset + 120).join('')) + ' +',
  );
}
const codeLines = groupedCodes.length
  ? [...groupedCodes.slice(0, -1), groupedCodes.at(-1).slice(0, -2) + ';']
  : ['  "";'];
const rawOutput = [
  '// Generated by scripts/generate-authoring-graph-field-metadata.mjs.',
  '// Do not edit. The reviewer checks all field effects against the full authoring schema.',
  'export const GRAPH_FIELD_PATHS: readonly string[] = Object.freeze([',
  ...groupedPaths,
  ']);',
  'export const GRAPH_FIELD_EFFECT_CODES =',
  ...codeLines,
  'export const GENERATED_GRAPH_FIELD_FINGERPRINTS: Readonly<Record<string, string>> = Object.freeze(',
  JSON.stringify(review.CURRENT_AUTHORING_GRAPH_FIELD_FINGERPRINTS, null, 2) + ',',
  ');',
  'export const REVIEWED_GRAPH_FIELD_FINGERPRINTS: Readonly<Record<string, string>> = Object.freeze(',
  JSON.stringify(review.EXPECTED_AUTHORING_GRAPH_FIELD_FINGERPRINTS, null, 2) + ',',
  ');',
  '',
].join('\n');
// Keep the checked-in generated module in exactly the same format as the
// editor's formatting checks, so --check never needs to alter files.
const formatResult = spawnSync(
  process.execPath,
  [path.join(editorRoot, 'node_modules/vite-plus/bin/vp'), 'fmt', `--stdin-filepath=${outputPath}`],
  { cwd: editorRoot, input: rawOutput, encoding: 'utf8' },
);
if (formatResult.error || formatResult.status !== 0)
  throw new Error(formatResult.stderr || String(formatResult.error));
const output = formatResult.stdout;

if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== output) {
    console.error(
      'Authoring graph metadata is stale. Run: node scripts/generate-authoring-graph-field-metadata.mjs',
    );
    process.exitCode = 1;
  } else {
    console.log(`Authoring graph metadata verified (${fields.length} fields).`);
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Generated authoring graph metadata (${fields.length} fields).`);
}
