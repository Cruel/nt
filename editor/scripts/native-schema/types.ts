import type { JsonSchema } from './generate';

// Boxes break recursive ownership cycles without exposing a JSON library in generated types.
export function generateCppTypes(schemas: Record<string, JsonSchema>): string {
  const declarations: string[] = [];
  const definitions: string[] = [];
  const identifier = (name: string) =>
    'field_' + name.replace(/[^a-zA-Z0-9]/gu, (char) => `_u${char.codePointAt(0)!.toString(16)}_`);
  for (const [rootName, root] of Object.entries(schemas)) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(rootName))
      throw new Error(`Invalid C++ contract name: ${rootName}`);
    const names = new Map<object, string>();
    const pending: [string, JsonSchema][] = [];
    const resolve = (schema: JsonSchema): JsonSchema => {
      if (!schema.$ref) return schema;
      if (typeof schema.$ref !== 'string') throw new Error('Schema reference must be a string');
      const ref = schema.$ref;
      if (ref === '#') return resolve(root);
      if (!ref.startsWith('#/')) throw new Error(`Unsupported schema reference ${ref}`);
      let target: unknown = root;
      for (const key of ref.slice(2).split('/'))
        target = (target as JsonSchema)[key.replace(/~1/g, '/').replace(/~0/g, '~')];
      if (!target || typeof target !== 'object') throw new Error(`Missing schema reference ${ref}`);
      return resolve(target as JsonSchema);
    };
    const type = (input: JsonSchema): string => {
      const schema = resolve(input);
      if (
        !schema.type &&
        !schema.$ref &&
        !schema.anyOf &&
        !schema.oneOf &&
        !schema.enum &&
        !('const' in schema)
      )
        return 'PersistableValue';
      if (!schema.enum && !('const' in schema)) {
        if (schema.type === 'string') return 'std::string';
        if (schema.type === 'number') return 'double';
        if (schema.type === 'integer') return 'std::int64_t';
        if (schema.type === 'boolean') return 'bool';
        if (schema.type === 'null') return 'std::nullptr_t';
      }
      let name = names.get(schema);
      if (!name) {
        name = names.size === 0 ? rootName : `${rootName}Node${names.size}`;
        names.set(schema, name);
        pending.push([name, schema]);
        declarations.push(`struct ${name};`);
      }
      return `std::shared_ptr<${name}>`;
    };
    type(root);
    for (let index = 0; index < pending.length; index++) {
      const [name, schema] = pending[index]!;
      const variants = (schema.oneOf ?? schema.anyOf) as JsonSchema[] | undefined;
      let body: string;
      if (variants) {
        body = `using Value = std::variant<${variants.map(type).join(', ')}>;\nValue value;`;
      } else if (schema.enum || 'const' in schema) {
        const values = (schema.enum ?? [schema.const]) as unknown[];
        body = `enum class Value { ${values.map((_, i) => `choice${i}`).join(', ')} };\nValue value;`;
        if (values.every((value) => typeof value === 'boolean'))
          body += `\nstatic constexpr std::array<bool, ${values.length}> literals{${values.join(', ')}};`;
        else if (values.every((value) => typeof value === 'number' && Number.isFinite(value)))
          body += `\nstatic constexpr std::array<double, ${values.length}> literals{${values.join(', ')}};`;
      } else if (schema.type === 'object') {
        const required = new Set((schema.required as string[]) ?? []);
        const fields = Object.entries((schema.properties as Record<string, JsonSchema>) ?? {}).map(
          ([key, property]) => {
            const fieldType = type(property);
            return `${required.has(key) ? fieldType : `std::optional<${fieldType}>`} ${identifier(key)};`;
          },
        );
        if (schema.additionalProperties && typeof schema.additionalProperties === 'object')
          fields.push(
            `std::map<std::string, ${type(schema.additionalProperties as JsonSchema)}> additional;`,
          );
        body = fields.join('\n');
      } else if (schema.type === 'array') {
        if (schema.prefixItems)
          body = `std::tuple<${(schema.prefixItems as JsonSchema[]).map(type).join(', ')}> value;`;
        else body = `std::vector<${type(schema.items as JsonSchema)}> value;`;
      } else if (Array.isArray(schema.type)) {
        body = `std::variant<${schema.type.map((entry) => type({ type: entry })).join(', ')}> value;`;
      } else {
        throw new Error(
          `Unsupported native structural type ${name}: ${Object.keys(schema).join(', ')}`,
        );
      }
      definitions.push(`struct ${name} {\n${body}\n};`);
    }
  }
  return [
    '// Generated by editor/scripts/generate-native-schema.mjs. Do not edit.',
    '// clang-format off',
    '#pragma once',
    '#include <array>',
    '#include <cstddef>',
    '#include <cstdint>',
    '#include <map>',
    '#include <memory>',
    '#include <optional>',
    '#include <string>',
    '#include <tuple>',
    '#include <variant>',
    '#include <vector>',
    'namespace noveltea::authoring::generated {',
    'struct PersistableValue { using Value = std::variant<std::nullptr_t, bool, double, std::string, std::vector<PersistableValue>, std::map<std::string, PersistableValue>>; Value value; };',
    ...declarations,
    ...definitions,
    '}',
    '// clang-format on',
    '',
  ].join('\n');
}
