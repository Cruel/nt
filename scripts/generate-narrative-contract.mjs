// Build-maintenance tool only. Production validation never invokes Node or the upstream checkout.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, cpSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';

const upstream = resolve(process.argv[2] ?? '../noveltea-skills');
const root = resolve(import.meta.dirname, '..');
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim();
if (execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], { cwd: upstream, encoding: 'utf8' }).trim()) {
  throw new Error('Generate only from a clean upstream checkout.');
}
// Resolve the upstream toolchain, not the editor's potentially different Zod release.
const runner = readFileSync(join(root, 'scripts/export-narrative-schema.mjs'), 'utf8');
const schema = JSON.parse(execFileSync('pnpm', ['exec', 'tsx', '--eval', runner], { cwd: upstream, encoding: 'utf8' }));
const inputs = ['src/schema.ts', 'src/catalog.ts', 'src/progression.ts', 'src/state.ts'];
const hashes = Object.fromEntries(inputs.map(path => [path, createHash('sha256').update(readFileSync(join(upstream, path))).digest('hex')]));
const output = join(root, 'tools/narrative/generated');
mkdirSync(output, { recursive: true });
writeFileSync(join(output, 'contract.json'), JSON.stringify({ repository: 'Cruel/noveltea-skills', revision, hashes, record: schema }, null, 2) + '\n');
writeFileSync(join(output, 'contract.hpp'), `// Generated by scripts/generate-narrative-contract.mjs; do not edit.\n#pragma once\n#include <string_view>\nnamespace noveltea::narrative {\ninline constexpr std::string_view contract_source = R"NTCATALOG(${JSON.stringify({ revision, record: schema })})NTCATALOG";\n}\n`);
for (const name of ['reference-story', 'planning-stages'])
  rmSync(join(root, 'tests/fixtures/narrative', name), { recursive: true, force: true });
cpSync(join(upstream, 'fixtures/reference-story'), join(root, 'tests/fixtures/narrative/reference-story'), { recursive: true });
cpSync(join(upstream, 'fixtures/planning-stages'), join(root, 'tests/fixtures/narrative/planning-stages'), { recursive: true });
const oracle = readFileSync(join(root, 'scripts/narrative-oracle.mjs'), 'utf8');
const cases = JSON.parse(execFileSync('pnpm', ['exec', 'tsx', '--eval', oracle], { cwd: upstream, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }));
writeFileSync(join(root, 'tests/fixtures/narrative/conformance.json'), JSON.stringify({ revision, cases }, null, 2) + '\n');
console.log(`Generated narrative contract, canonical fixtures and ${cases.length} oracle cases from ${revision}`);
